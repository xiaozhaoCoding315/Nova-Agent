import { execFileSync } from 'node:child_process'
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const names = {
  zhipu: 'Zhipu',
  dashscope: 'Qwen',
  deepseek: 'DeepSeek',
  moonshot: 'Moonshot',
  minimax: 'Minimax',
  siliconflow: 'SiliconCloud',
  volcengine: 'Volcengine',
  openai: 'OpenAI',
  anthropic: 'Anthropic',
  gemini: 'Gemini',
  xai: 'XAI',
  mistral: 'Mistral',
  groq: 'Groq',
  openrouter: 'OpenRouter',
  ollama: 'Ollama',
}

const dir = mkdtempSync(join(tmpdir(), 'nova-provider-icons-'))
try {
  // shell: true is required on Windows, where npm is npm.cmd and Node's
  // execFileSync does not resolve .cmd shims without a shell.
  const packed = execFileSync(
    'npm', ['pack', '@lobehub/icons@6.13.0', '--silent'],
    { cwd: dir, encoding: 'utf8', shell: true },
  ).trim().split('\n').pop()
  execFileSync('tar', ['-xzf', packed], { cwd: dir, shell: true })

  const entries = []
  for (const [id, name] of Object.entries(names)) {
    const source = readFileSync(
      join(dir, 'package', 'es', name, 'components', 'Mono.mjs'), 'utf8',
    )
    const paths = [...source.matchAll(/d: "([^"]+)"/g)].map((match) => match[1])
    if (!paths.length) throw new Error(`no paths for ${name}`)
    entries.push([id, paths])
  }

  let output = [
    '// Brand icon paths vendored from @lobehub/icons v6.13.0 (MIT License).',
    '// Source: https://github.com/lobehub/lobe-icons',
    '// Generated by scripts/extract-provider-icons.mjs — do not edit by hand.',
    '',
    'export const PROVIDER_ICON_PATHS: Record<string, string[]> = {',
  ].join('\n')
  for (const [id, paths] of entries) {
    output += `  ${id}: [\n`
    for (const path of paths) output += `    ${JSON.stringify(path)},\n`
    output += '  ],\n'
  }
  output += '}\n'
  writeFileSync(join(process.cwd(), 'src', 'lib', 'provider-icons.ts'), output)
} finally {
  rmSync(dir, { recursive: true, force: true })
}
